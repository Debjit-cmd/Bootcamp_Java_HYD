package com.JavaOperator;

public class AssignmentOperator {

	public static void main(String[] args) {

        int a = 10;
        System.out.println("Initial value of a: " + a);
        int var = a;
        System.out.println("Var using =:"+var);
        var+=a;
        System.out.println("Var using +=:"+var);
        var*=a;
        System.out.println("Var using *=:"+var);


	}

}
