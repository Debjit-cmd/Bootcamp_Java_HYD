package DecisionMakingStatements;

public class if_else_if {

	public static void main(String[] args) {
		String city = "Meerut123";
		if(city == "Meerut") {
			System.out.println("City is Meerut");
		}
		else if (city == "Noida") {
			System.out.println("City is Noida");
		}
		else {
			System.out.println(city);
		}

	}

}
